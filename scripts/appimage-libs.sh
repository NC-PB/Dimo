#!/usr/bin/env bash
# System libraries of the Linux AppImage (T3.23). Runs on the Ubuntu machine that built the
# AppImage (the linux job of .github/workflows/release.yml), because only there dpkg knows which
# package each bundled file comes from.
#
# Lists every file of the AppImage with its package, version, source package and source
# version, in the format of scripts/appimage/libs.txt. Left out are only the files listed in
# not_from_a_package below: DimoMark's own files, the AppImage tools (scripts/appimage/other.tsv),
# the copyright files themselves and caches generated while building. The generator
# scripts/third-party-licenses.mjs reads libs.txt and the Debian copyright files in
# scripts/appimage/copyright/ to write the "Linux AppImage" part of THIRD_PARTY_LICENSES.
#
# Usage: ./scripts/appimage-libs.sh --check  <AppImage>   fail if the committed data differs
#        ./scripts/appimage-libs.sh --update <AppImage>   write libs.txt and the copyright files
# After --update see scripts/appimage/README.md.
set -euo pipefail
shopt -s nullglob

if [[ $# -ne 2 || ( "$1" != "--check" && "$1" != "--update" ) ]]; then
  echo "usage: $0 --check|--update <AppImage>" >&2
  exit 2
fi
mode="$1"
appimage="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"
cd "$(dirname "$0")/.."
DATA=scripts/appimage
# Where dpkg keeps the copyright files; another folder only for testing this script elsewhere.
DOCS="${APPIMAGE_LIBS_DOCS:-/usr/share/doc}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
(cd "$work" && "$appimage" --appimage-extract >/dev/null)
appdir="$work/squashfs-root"

# Files that come from no Ubuntu package. Keep this list short and explicit.
not_from_a_package() {
  case "$1" in
    AppRun | AppRun.wrapped | apprun-hooks/*) return 0 ;;             # other.tsv
    DimoMark.png | usr/bin/dimo-desktop | usr/lib/DimoMark/*) return 0 ;; # DimoMark itself
    usr/share/applications/DimoMark.desktop) return 0 ;;
    usr/share/icons/hicolor/*/apps/dimo-desktop.png) return 0 ;;
    usr/share/doc/*/copyright) return 0 ;;                              # the copyright files
    usr/lib/*.cache | usr/share/glib-2.0/schemas/gschemas.compiled) return 0 ;; # generated
  esac
  return 1
}

# The system path of a bundled file: linuxdeploy copies libraries flat into usr/lib and keeps
# the folders of plugins below the library folder; other files keep their path.
candidates() {
  case "$1" in
    usr/lib/x86_64-linux-gnu/*) echo "/$1" ;;
    usr/lib/*/*) echo "/usr/lib/x86_64-linux-gnu/${1#usr/lib/}" ;;
    usr/lib/*) printf '%s\n' "/usr/lib/x86_64-linux-gnu/${1#usr/lib/}" "/lib/x86_64-linux-gnu/${1#usr/lib/}" ;;
    *) echo "/$1" ;;
  esac
}

{
  echo "# Files the Linux AppImage takes from Ubuntu 22.04 packages (T3.23)."
  echo "# Generated by scripts/appimage-libs.sh, do not edit. Columns: file, package, version, source package, source version."
  (cd "$appdir" && find . -type f | sed 's#^\./##') |
    LC_ALL=C sort |
    while read -r file; do
      if not_from_a_package "$file"; then
        continue
      fi
      package=""
      for path in $(candidates "$file"); do
        package="$(dpkg -S "$path" 2>/dev/null | grep -v '^diversion by' | head -n 1 | sed 's/: .*//; s/:.*//')" || true
        [[ -n "$package" ]] && break
      done
      fields=""
      if [[ -n "$package" ]]; then
        fields="$(dpkg-query -W -f '${Version}\t${source:Package}\t${source:Version}\n' "$package" 2>/dev/null | head -n 1)" || true
      fi
      if [[ -z "$package" || -z "$fields" ]]; then
        printf '%s\t?\t?\t?\t?\n' "$file"
      else
        printf '%s\t%s\t%s\n' "$file" "$package" "$fields"
      fi
    done
} >"$work/libs.txt"

status=0
if grep -q $'\t?\t' "$work/libs.txt"; then
  echo "files of no known package (add them to not_from_a_package only if they are DimoMark's):" >&2
  grep $'\t?\t' "$work/libs.txt" | cut -f1 >&2
  status=1
fi

# The copyright file of each package, unchanged. Packages of one source must share one file.
mkdir -p "$work/copyright"
while IFS=$'\t' read -r _ package _ source _; do
  [[ "$package" == "?" ]] && continue
  doc="$DOCS/$package/copyright"
  if [[ ! -f "$doc" ]]; then
    echo "no copyright file for package $package" >&2
    status=1
  elif [[ -f "$work/copyright/$source" ]] && ! cmp -s "$doc" "$work/copyright/$source"; then
    echo "packages of $source have different copyright files ($package); handle by hand" >&2
    status=1
  else
    cp "$doc" "$work/copyright/$source"
  fi
done < <(grep -v '^#' "$work/libs.txt" | LC_ALL=C sort -t $'\t' -k2,2 -u)

if [[ "$mode" == "--update" ]]; then
  cp "$work/libs.txt" "$DATA/libs.txt"
  rm -rf "$DATA/copyright"
  cp -R "$work/copyright" "$DATA/copyright"
  echo "updated $DATA; see scripts/appimage/README.md for the next steps"
else
  if ! diff -u "$DATA/libs.txt" "$work/libs.txt"; then
    echo "scripts/appimage/libs.txt differs from the AppImage (diff above)." >&2
    status=1
  fi
  if ! diff -r "$DATA/copyright" "$work/copyright" >/dev/null; then
    diff -rq "$DATA/copyright" "$work/copyright" >&2 || true
    echo "scripts/appimage/copyright/ differs from the copyright files of the packages." >&2
    status=1
  fi
  if [[ $status -eq 0 ]]; then
    echo "AppImage files match scripts/appimage ($(grep -vc '^#' "$DATA/libs.txt") files)"
  else
    echo "Update the data as described in scripts/appimage/README.md." >&2
  fi
fi
exit $status
