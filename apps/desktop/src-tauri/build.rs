//! Generates the Tauri context (config, capabilities, icons).
//!
//! App commands come from `commands.txt` and are declared in the app manifest, so each one gets
//! an `allow-<command>` permission. One generated set, `allow-app-commands`, groups them all and
//! the capability references only that set, so the webview can call only listed commands
//! (NFR-SEC-01).
//!
//! On Windows the app executable gets `windows-app-manifest.xml` (long path aware, R.12).

fn main() {
    println!("cargo:rerun-if-changed=commands.txt");
    let table = std::fs::read_to_string("commands.txt")
        .unwrap_or_else(|err| panic!("cannot read commands.txt: {err}"));
    // The manifest wants `&'static str`; the build script is short lived, so leaking is fine.
    let names: &'static [&'static str] = Vec::leak(
        table
            .lines()
            .map(str::trim)
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
            .map(|line| &*Box::leak(line.to_owned().into_boxed_str()))
            .collect(),
    );
    if let Err(err) = write_command_permission_set(names) {
        panic!("cannot write the command permission set: {err}");
    }
    let manifest = tauri_build::AppManifest::new().commands(names);
    // The Windows manifest of the app executable: the default one plus long path awareness.
    println!("cargo:rerun-if-changed=windows-app-manifest.xml");
    let windows = tauri_build::WindowsAttributes::new()
        .app_manifest(include_str!("windows-app-manifest.xml"));
    let attributes = tauri_build::Attributes::new()
        .app_manifest(manifest)
        .windows_attributes(windows);
    if let Err(err) = tauri_build::try_build(attributes) {
        panic!("tauri build failed: {err:#}");
    }
    embed_test_manifest();
}

/// Writes `permissions/generated/app-commands.toml`, the permission set `allow-app-commands`
/// that contains `allow-<command>` for every command of the table. The file is git ignored.
fn write_command_permission_set(names: &[&str]) -> std::io::Result<()> {
    let mut toml = String::from(
        "# Generated by build.rs from commands.txt. Do not edit.\n\n[[set]]\n\
         identifier = \"allow-app-commands\"\n\
         description = \"Every app command of commands.txt, for the main window.\"\n\
         permissions = [\n",
    );
    for name in names {
        toml.push_str("  \"allow-");
        toml.push_str(&name.replace('_', "-"));
        toml.push_str("\",\n");
    }
    toml.push_str("]\n");
    let dir = std::path::Path::new("permissions").join("generated");
    std::fs::create_dir_all(&dir)?;
    let path = dir.join("app-commands.toml");
    // Write only when the content changes, so an unchanged table never retriggers the build.
    if std::fs::read_to_string(&path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(&path, toml)?;
    }
    Ok(())
}

/// Windows (MSVC) test executables get the Common Controls v6 manifest that tauri-build only
/// embeds into the app executable; without it they fail to start with
/// `STATUS_ENTRYPOINT_NOT_FOUND`. Applies to test targets only, so the app keeps its manifest.
fn embed_test_manifest() {
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    if target_os != "windows" || target_env != "msvc" {
        return;
    }
    let dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    let manifest = std::path::Path::new(&dir).join("windows-test-manifest.xml");
    println!("cargo:rerun-if-changed={}", manifest.display());
    println!("cargo:rustc-link-arg-tests=/MANIFEST:EMBED");
    println!(
        "cargo:rustc-link-arg-tests=/MANIFESTINPUT:{}",
        manifest.display()
    );
}
